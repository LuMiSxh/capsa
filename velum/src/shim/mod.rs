//! Owns the `claude` shim: a POSIX sh script on PATH that starts Claude Code through
//! `velum run`, so every start goes through the sandbox.

#[cfg(test)]
mod tests;

use crate::check::{Check, Status};
use crate::srt::sh_quote;
use crate::writable;
use anyhow::{Context, Result};
use capsa_core::exit::Outcome;
use capsa_core::hint::{Hinted, ResultExt};
use capsa_core::which;
use serde_json::Value;
use std::ffi::OsStr;
use std::io::Read;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

/// The shim's file name.
const NAME: &str = "claude";
/// The line that marks a file as velum's shim. Only files with this line are written over or
/// removed.
const MARKER: &str = "# velum shim";
/// How much of a file is read when looking for the marker.
const PROBE_BYTES: u64 = 4096;

/// The shim directory when `--dir` is not given.
pub fn default_dir(home: &str) -> PathBuf {
    Path::new(home).join(".local/bin")
}

/// Returns the shim script that starts the real claude at `real` through the velum binary at
/// `velum`. Both are absolute: a `velum` found through PATH could be planted.
pub fn script(real: &Path, velum: &Path) -> String {
    format!(
        "#!/bin/sh\n\
         {MARKER}\n\
         # Generated by velum shim install. Remove it with velum shim uninstall.\n\
         exec {velum} run -- {real} --dangerously-skip-permissions \"$@\"\n",
        velum = sh_quote(velum),
        real = sh_quote(real),
    )
}

/// Returns the velum path baked into the shim at `path`, if the script has the absolute form.
pub fn baked_velum(path: &Path) -> Option<PathBuf> {
    let text = std::fs::read_to_string(path).ok()?;
    let word = text.lines().find_map(|line| line.strip_prefix("exec "))?;
    let mut rest = word.strip_prefix('\'')?;
    let mut out = String::new();
    loop {
        let end = rest.find('\'')?;
        out.push_str(&rest[..end]);
        rest = &rest[end + 1..];
        // `sh_quote` writes an embedded quote as `'\''`.
        match rest.strip_prefix("\\''") {
            Some(more) => {
                out.push('\'');
                rest = more;
            }
            None => return Some(PathBuf::from(out)),
        }
    }
}

/// Returns whether the velum the shim in `dir` runs still exists. `None` when there is no shim.
pub fn velum_check(dir: &Path) -> Option<Check> {
    let target = dir.join(NAME);
    if !is_shim(&target) {
        return None;
    }
    Some(match baked_velum(&target) {
        Some(velum) if velum.exists() => Check::new(
            "shim velum",
            Status::Ok,
            format!("runs {}", velum.display()),
        ),
        Some(velum) => Check::new(
            "shim velum",
            Status::Warn,
            format!(
                "{} no longer exists; run velum shim install",
                velum.display()
            ),
        ),
        None => Check::new(
            "shim velum",
            Status::Warn,
            "runs `velum` from PATH; run velum shim install to bake the absolute path",
        ),
    })
}

/// Returns whether `path` is a velum shim. A file that cannot be read is not.
pub fn is_shim(path: &Path) -> bool {
    let mut head = Vec::new();
    let readable = std::fs::File::open(path)
        .and_then(|file| file.take(PROBE_BYTES).read_to_end(&mut head))
        .is_ok();
    readable
        && head
            .split(|byte| *byte == b'\n')
            .any(|line| line == MARKER.as_bytes())
}

/// Returns whether anything exists at `path`, a broken symlink included.
fn exists(path: &Path) -> bool {
    path.symlink_metadata().is_ok()
}

/// Writes the shim into `dir`, pointing at the first claude on `path` outside `dir` and
/// at the velum binary `velum` (absolute). A file at that place that velum did not write
/// is refused.
pub fn install(dir: &Path, path: &OsStr, velum: &Path, dry_run: bool) -> Result<Outcome> {
    let target = dir.join(NAME);
    if exists(&target) && !is_shim(&target) {
        return Err(Hinted::new(
            format!("{} exists and is not a velum shim", target.display()),
            "move it aside first",
        )
        .into());
    }
    if !velum.is_absolute() {
        return Err(Hinted::new(
            format!("the velum path {} is not absolute", velum.display()),
            "run velum by its absolute path",
        )
        .into());
    }
    let real = real_claude(dir, path)?;
    let text = script(&real, velum);
    if dry_run {
        println!("would write {}:\n{text}", target.display());
        return Ok(Outcome::Found);
    }
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    std::fs::write(&target, &text).with_context(|| format!("writing {}", target.display()))?;
    std::fs::set_permissions(&target, std::fs::Permissions::from_mode(0o755))
        .with_context(|| format!("chmod {}", target.display()))?;
    println!("installed {} -> {}", target.display(), real.display());
    Ok(Outcome::Found)
}

/// Fails with a hint when the sandbox of `settings` could write `velum` or the real claude,
/// which the shim runs outside the sandbox.
pub fn ensure_targets_not_writable(
    settings: &Value,
    dir: &Path,
    path: &OsStr,
    velum: &Path,
) -> Result<()> {
    writable::ensure_not_writable(settings, "velum", velum).hinted()?;
    let real = real_claude(dir, path)?;
    writable::ensure_not_writable(settings, "claude", &real).hinted()?;
    Ok(())
}

/// Returns the first claude on the absolute entries of `path` outside `dir`, as an absolute path.
pub fn real_claude(dir: &Path, path: &OsStr) -> Result<PathBuf> {
    let Some((_, found)) = which::find_on_path(NAME, path, Some(dir)) else {
        return Err(Hinted::new(
            format!("no claude on PATH outside {}", dir.display()),
            "install Claude Code first",
        )
        .into());
    };
    if is_shim(&found) {
        return Err(Hinted::new(
            format!("{} is already a velum shim", found.display()),
            "put the real claude on PATH, or run velum shim uninstall first",
        )
        .into());
    }
    std::path::absolute(&found).with_context(|| format!("resolving {}", found.display()))
}

/// Removes the shim from `dir`. A file that velum did not write is left alone.
pub fn uninstall(dir: &Path, dry_run: bool) -> Result<Outcome> {
    let target = dir.join(NAME);
    if !exists(&target) {
        println!("no shim at {}", target.display());
        return Ok(Outcome::Empty);
    }
    if !is_shim(&target) {
        return Err(Hinted::new(
            format!("{} is not a velum shim; not removed", target.display()),
            "remove it by hand if it is yours",
        )
        .into());
    }
    if dry_run {
        println!("would remove {}", target.display());
        return Ok(Outcome::Found);
    }
    std::fs::remove_file(&target).with_context(|| format!("removing {}", target.display()))?;
    println!("removed {}", target.display());
    Ok(Outcome::Found)
}

/// Returns the shim's state in `dir`, and where `dir` sits on PATH.
pub fn status(dir: &Path, path: &OsStr) -> Vec<Check> {
    let target = dir.join(NAME);
    let installed = if !exists(&target) {
        let detail = format!("none in {}; run velum shim install", dir.display());
        Check::new("shim", Status::Warn, detail)
    } else if is_shim(&target) {
        Check::new(
            "shim",
            Status::Ok,
            format!("installed at {}", target.display()),
        )
    } else {
        let detail = format!("{} is not a velum shim", target.display());
        Check::new("shim", Status::Fail, detail)
    };
    let mut checks = vec![installed, position_check(dir, path)];
    checks.extend(velum_check(dir));
    checks
}

/// Returns whether `dir` comes before the real claude on PATH.
pub fn position_check(dir: &Path, path: &OsStr) -> Check {
    let shown = dir.display();
    let Some(own) = which::path_index(path, dir) else {
        return Check::new("shim dir", Status::Warn, format!("{shown} is not on PATH"));
    };
    match which::find_on_path(NAME, path, Some(dir)) {
        None => {
            let detail = format!("{shown} is on PATH, but no claude is outside it");
            Check::new("shim dir", Status::Warn, detail)
        }
        Some((index, real)) if own < index => {
            let detail = format!("{shown} comes before {} in PATH", real.display());
            Check::new("shim dir", Status::Ok, detail)
        }
        Some((_, real)) => {
            let detail = format!(
                "{shown} comes after {}, so the real claude runs first",
                real.display()
            );
            Check::new("shim dir", Status::Warn, detail)
        }
    }
}
