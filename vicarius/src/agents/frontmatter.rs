//! Derives a DeepSeek variant of an agent file by editing its top-level frontmatter lines.

use std::ops::Range;

use thiserror::Error;

const FENCE: &str = "---";
const MARKER_PREFIX: &str = "# Generated by vicarius from ";
const MARKER_SUFFIX: &str = "; edits are overwritten on sync.";

/// Why an agent file cannot be derived.
#[derive(Debug, Error, PartialEq, Eq)]
pub enum DeriveError {
    /// The file does not start with a `---` line.
    #[error("the agent file does not start with a `---` line")]
    NoOpeningFence,
    /// The frontmatter has no closing `---` line.
    #[error("the frontmatter has no closing `---` line")]
    NoClosingFence,
    /// The file is a derived variant, so it is not a source.
    #[error("the file is already a derived variant")]
    AlreadyDerived,
    /// The description is a form that cannot take the DeepSeek note.
    #[error("the description cannot take the DeepSeek note: {0}")]
    Description(&'static str),
}

/// Returns the DeepSeek variant of the agent file `source`, derived for `from` on `model`.
///
/// Only the top-level frontmatter keys are edited: `name` and `model` are set, and `description`
/// gets the DeepSeek note. Every other line, the body included, is kept byte for byte, and so are
/// the line endings.
///
/// # Errors
/// Fails when the frontmatter is not fenced, when `source` is already a derived variant, or when
/// the description is a form that cannot take the note.
pub fn derive(source: &str, from: &str, model: &str) -> Result<String, DeriveError> {
    let mut lines = split_lines(source);
    let close = closing_fence(&lines)?;
    if lines[1..close].iter().any(|line| is_marker(&line.text)) {
        return Err(DeriveError::AlreadyDerived);
    }
    let nl = newline(&lines);
    lines.insert(
        1,
        Line::new(format!("{MARKER_PREFIX}{from}.md{MARKER_SUFFIX}"), nl),
    );
    set_key(&mut lines, "name", format!("name: {from}-ds"), nl, 2);
    let after_name = key_span(&lines, "name").map_or(2, |span| span.end);
    set_key(
        &mut lines,
        "model",
        format!("model: {model}"),
        nl,
        after_name,
    );
    extend_description(&mut lines, from, model, nl)?;
    Ok(join(&lines))
}

/// Returns whether the frontmatter of `text` carries the marker that `derive` writes.
pub fn is_derived(text: &str) -> bool {
    let lines = split_lines(text);
    closing_fence(&lines)
        .is_ok_and(|close| lines[1..close].iter().any(|line| is_marker(&line.text)))
}

/// A source line without its line ending, which is written back as it was read.
struct Line {
    text: String,
    eol: &'static str,
}

impl Line {
    fn new(text: String, eol: &'static str) -> Self {
        Self { text, eol }
    }
}

fn split_lines(source: &str) -> Vec<Line> {
    source
        .split_inclusive('\n')
        .map(|raw| {
            let (text, eol) = if let Some(text) = raw.strip_suffix("\r\n") {
                (text, "\r\n")
            } else if let Some(text) = raw.strip_suffix('\n') {
                (text, "\n")
            } else {
                (raw, "")
            };
            Line::new(text.to_owned(), eol)
        })
        .collect()
}

fn join(lines: &[Line]) -> String {
    let mut out = String::new();
    for line in lines {
        out.push_str(&line.text);
        out.push_str(line.eol);
    }
    out
}

fn newline(lines: &[Line]) -> &'static str {
    if lines.iter().any(|line| line.eol == "\r\n") {
        "\r\n"
    } else {
        "\n"
    }
}

fn is_marker(text: &str) -> bool {
    text.strip_prefix(MARKER_PREFIX)
        .is_some_and(|rest| rest.ends_with(MARKER_SUFFIX))
}

fn closing_fence(lines: &[Line]) -> Result<usize, DeriveError> {
    if lines.first().is_none_or(|line| line.text != FENCE) {
        return Err(DeriveError::NoOpeningFence);
    }
    lines
        .iter()
        .skip(1)
        .position(|line| line.text == FENCE)
        .map(|index| index + 1)
        .ok_or(DeriveError::NoClosingFence)
}

/// Returns the key of a top-level `key:` line, which starts at column 0.
fn top_key(text: &str) -> Option<&str> {
    let end = text.find(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '-'))?;
    let (key, rest) = text.split_at(end);
    (!key.is_empty() && rest.starts_with(':')).then_some(key)
}

fn is_continuation(text: &str) -> bool {
    text.trim().is_empty() || text.starts_with([' ', '\t'])
}

/// Returns the lines of the top-level `key`, from its key line to its last non-blank line.
fn key_span(lines: &[Line], key: &str) -> Option<Range<usize>> {
    let close = closing_fence(lines).ok()?;
    let start = (1..close).find(|&index| top_key(&lines[index].text) == Some(key))?;
    let body = &lines[start + 1..close];
    let run = body
        .iter()
        .take_while(|line| is_continuation(&line.text))
        .count();
    let last = body[..run]
        .iter()
        .rposition(|line| !line.text.trim().is_empty());
    Some(start..last.map_or(start + 1, |offset| start + 2 + offset))
}

fn set_key(lines: &mut Vec<Line>, key: &str, text: String, nl: &'static str, absent_at: usize) {
    let line = Line::new(text, nl);
    match key_span(lines, key) {
        Some(span) => {
            let start = span.start;
            lines.drain(span);
            lines.insert(start, line);
        }
        None => lines.insert(absent_at, line),
    }
}

fn extend_description(
    lines: &mut Vec<Line>,
    from: &str,
    model: &str,
    nl: &'static str,
) -> Result<(), DeriveError> {
    let sentence =
        format!("DeepSeek variant of {from} on {model}, billed to the DeepSeek API credit.");
    let Some(span) = key_span(lines, "description") else {
        let close = closing_fence(lines)?;
        lines.insert(close, Line::new(format!("description: {sentence}"), nl));
        return Ok(());
    };
    let first = lines[span.start].text.as_str();
    let value = first
        .strip_prefix("description:")
        .unwrap_or(first)
        .trim_start();
    match value.chars().next() {
        Some('|' | '>') => {
            let indent = block_indent(lines, &span);
            lines.insert(span.end, Line::new(format!("{indent}{sentence}"), nl));
        }
        Some(quote @ ('"' | '\'')) => {
            let (index, at) = closing_quote(lines, span, quote).ok_or(DeriveError::Description(
                "the quoted description is not closed",
            ))?;
            let text = &lines[index].text;
            let edited = format!("{} {sentence}{}", &text[..at], &text[at..]);
            lines[index].text = edited;
        }
        Some('[' | '{') => {
            return Err(DeriveError::Description(
                "flow collections cannot take the note",
            ));
        }
        _ => {
            let index = span.end - 1;
            let text = &lines[index].text;
            let at = plain_end(text);
            let edited = format!("{} {sentence}{}", &text[..at], &text[at..]);
            lines[index].text = edited;
        }
    }
    Ok(())
}

/// Returns the indentation of the first content line of a block scalar, or two spaces when the
/// block is empty.
fn block_indent(lines: &[Line], span: &Range<usize>) -> String {
    lines[span.start + 1..span.end]
        .iter()
        .map(|line| line.text.as_str())
        .find(|text| !text.trim().is_empty())
        .map_or_else(
            || "  ".to_owned(),
            |text| text[..text.len() - text.trim_start().len()].to_owned(),
        )
}

/// Returns the line index and byte offset of the quote that closes the scalar opened by `quote`.
fn closing_quote(lines: &[Line], span: Range<usize>, quote: char) -> Option<(usize, usize)> {
    let mut escaped = false;
    for index in span.clone() {
        let text = lines[index].text.as_str();
        let skip = if index == span.start {
            text.find(quote).map_or(0, |at| at + 1)
        } else {
            0
        };
        let mut chars = text[skip..].char_indices().peekable();
        while let Some((offset, c)) = chars.next() {
            let at = skip + offset;
            if quote == '"' {
                if escaped {
                    escaped = false;
                } else if c == '\\' {
                    escaped = true;
                } else if c == '"' {
                    return Some((index, at));
                }
            } else if c == '\'' && chars.next_if(|&(_, next)| next == '\'').is_none() {
                return Some((index, at));
            }
        }
    }
    None
}

/// Returns the offset where a plain scalar ends, before any ` #` comment and trailing spaces.
fn plain_end(text: &str) -> usize {
    let content = text.find(" #").map_or(text, |at| &text[..at]);
    content.trim_end().len()
}
